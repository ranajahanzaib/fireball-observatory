pub fn get_shower_name(code: &str) -> String {
    let clean = code.trim();
    if clean.is_empty() || clean == "..." {
        return "Sporadic".to_string();
    }

    match clean.to_uppercase().as_str() {
        "GEM" => "Geminids".to_string(),
        "PER" => "Perseids".to_string(),
        "ORI" => "Orionids".to_string(),
        "QUA" => "Quadrantids".to_string(),
        "ETA" => "eta Aquariids".to_string(),
        "LYR" => "Lyrids".to_string(),
        "LEO" => "Leonids".to_string(),
        "URS" => "Ursids".to_string(),
        "CAP" => "alpha Capricornids".to_string(),
        "SDA" => "Southern delta Aquariids".to_string(),
        "NDA" => "Northern delta Aquariids".to_string(),
        "NTA" | "TAW" => "Northern Taurids".to_string(),
        "STA" => "Southern Taurids".to_string(),
        "MON" => "Monocerotids".to_string(),
        "HYD" => "sigma Hydrids".to_string(),
        "COM" => "Coma Berenicids".to_string(),
        "AND" => "Andromedids".to_string(),
        "DRA" | "GIA" => "Draconids".to_string(),
        "AUR" => "Aurigids".to_string(),
        "EVI" => "eta Virginids".to_string(),
        "GNO" => "gamma Normids".to_string(),
        "PUP" => "pi Puppids".to_string(),
        "ELY" => "eta Lyrids".to_string(),
        "JBO" => "June Bootids".to_string(),
        "PAU" => "Piscis Austrinids".to_string(),
        "KCG" => "kappa Cygnids".to_string(),
        "SPE" => "September epsilon Perseids".to_string(),
        "OCT" => "October Camelopardalids".to_string(),
        "LMI" => "Leonis Minorids".to_string(),
        "DLE" => "Daytime Leonids".to_string(),
        "ARI" => "Daytime Arietids".to_string(),
        "ZCA" => "zeta Cancrids".to_string(),
        "DAU" => "Daytime Aurigids".to_string(),
        "BUM" => "Daytime beta Ursae Majorids".to_string(),
        "AVB" => "alpha Virginids".to_string(),
        "SZC" => "Daytime sextantids".to_string(),
        "TPC" => "tau Piscids".to_string(),
        "EPC" => "epsilon Piscids".to_string(),
        "OCC" => "October Cygnids".to_string(),
        "EUM" => "epsilon Ursae Majorids".to_string(),
        "NOO" => "Northern October Orionids".to_string(),
        "XRI" => "x Arietids".to_string(),
        "NZP" => "Northern zeta Perseids".to_string(),
        "SZP" => "Southern zeta Perseids".to_string(),
        other => format!("Shower {}", other),
    }
}
